class RegisterSerializer(serializers.ModelSerializer):
    username = serializers.CharField(required=False, allow_blank=True)
    password = serializers.CharField(write_only=True, required=True, validators=[validate_password])
    confirm_password = serializers.CharField(write_only=True, required=True)
    full_name = serializers.CharField(write_only=True, required=False, allow_blank=True)

    class Meta:
        model = User
        fields = ('username', 'email', 'password', 'confirm_password', 'full_name', 'role', 'phone_number')

    def validate(self, attrs):
        if attrs['password'] != attrs['confirm_password']:
            raise serializers.ValidationError({"password": "Passwords do not match."})

        # Single Store Owner Restriction
        role = attrs.get('role', UserRole.CUSTOMER)
        if role == UserRole.STORE_OWNER:
            if User.objects.filter(role=UserRole.STORE_OWNER).exists():
                raise serializers.ValidationError({
                    "role": "Store owner registration is closed. Only a single authorized store owner account is permitted."
                })

        # Email Domain DNS Check
        email = attrs.get('email', '').strip()
        if '@' in email:
            domain = email.split('@')[-1].strip()
            try:
                socket.getaddrinfo(domain, None)
            except (socket.gaierror, IndexError):
                raise serializers.ValidationError({
                    "email": f"The email domain '@{domain}' does not exist or cannot receive mail."
                })

        return attrs

    def create(self, validated_data):
        validated_data.pop('confirm_password', None)
        full_name = validated_data.pop('full_name', '')
        
        first_name = ''
        last_name = ''
        if full_name:
            name_parts = full_name.strip().split(' ', 1)
            first_name = name_parts[0]
            if len(name_parts) > 1:
                last_name = name_parts[1]

        email = validated_data['email']
        username = validated_data.get('username') or email.split('@')[0]

        # Ensure username uniqueness if autogenerated or custom
        base_username = username
        counter = 1
        while User.objects.filter(username=username).exists():
            username = f"{base_username}{counter}"
            counter += 1

        user = User.objects.create_user(
            username=username,
            email=email,
            password=validated_data['password'],
            first_name=first_name,
            last_name=last_name,
            role=validated_data.get('role', 'customer'),
            phone_number=validated_data.get('phone_number', '')
        )
        return user


